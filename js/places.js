export function nearestPlace(point) {
  let best = places[0];
  let bestDistance = Infinity;
  for (const place of places) {
    const distance = haversineMeters(point, place);
    if (distance < bestDistance) {
      best = place;
      bestDistance = distance;
    }
  }
  return best;
}
